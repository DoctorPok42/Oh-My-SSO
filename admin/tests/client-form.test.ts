import { describe, expect, it } from "vitest";
import { clientBody, draftFromClient, emptyDraft } from "@/lib/client-form";
import type { Client } from "@/lib/types";

describe("client form <-> Admin API body", () => {
  it("creates a confidential OIDC client", () => {
    const d = { ...emptyDraft("oidc"), name: " Payroll ", redirectUris: "https://p/cb\n", accessTtlMinutes: "15" };
    const body = clientBody(d, "create");
    expect(body).toMatchObject({
      protocol: "oidc",
      name: "Payroll",
      public: false,
      redirect_uris: ["https://p/cb"],
      token_endpoint_auth_method: "client_secret_basic",
      require_pkce: true,
      access_token_ttl: 900,
      refresh_token_ttl: 0,
    });
    expect(body).not.toHaveProperty("client_id"); // empty: generated by the server
    expect(body).not.toHaveProperty("pairwise");
  });

  it("forces 'none' and PKCE for a public client", () => {
    const body = clientBody({ ...emptyDraft("oidc"), isPublic: true, requirePkce: false }, "create");
    expect(body).toMatchObject({ public: true, token_endpoint_auth_method: "none", require_pkce: true });
  });

  it("creates a SAML client with its certificate", () => {
    const body = clientBody(
      {
        ...emptyDraft("saml2"),
        entityId: "https://sp/md",
        acsUrl: "https://sp/acs",
        certificatePem: "PEM",
        pairwise: true,
      },
      "create",
    );
    expect(body).toMatchObject({ protocol: "saml2", entity_id: "https://sp/md", pairwise: true });
    expect(body.certificates).toEqual([{ pem: "PEM", not_before: null, not_after: null }]);
    expect(body).not.toHaveProperty("redirect_uris");
  });

  it("never sends create-only fields on update (the API refuses them)", () => {
    for (const p of ["oidc", "saml2"] as const) {
      const body = clientBody({ ...emptyDraft(p), clientId: "x", certificatePem: "PEM", pairwise: true }, "update");
      for (const k of ["protocol", "client_id", "public", "pairwise", "certificates"])
        expect(body).not.toHaveProperty(k);
    }
  });

  it("reads a client back into the form", () => {
    const client = {
      id: "1",
      name: "App",
      protocol: "oidc",
      status: "inactive",
      managed_by: "ui",
      client_id: "app",
      created_at: "",
      require_consent: true,
      subject_type: "public",
      mfa_policy: "required",
      mfa_methods: ["totp"],
      client_scopes: [{ id: "s1", name: "x", protocol: "oidc", required: true }],
      allowed_roles: [{ id: "r1", name: "r" }],
      allowed_groups: [],
      attribute_mappings: null,
      oidc: {
        client_type: "public",
        has_secret: false,
        redirect_uris: ["https://a", "https://b"],
        post_logout_redirect_uris: [],
        standard_scopes: ["openid"],
        grant_types: [],
        token_endpoint_auth_method: "none",
        require_pkce: true,
        access_token_ttl: 600,
        refresh_token_ttl: 86400,
        id_token_ttl: 0,
      },
    } satisfies Client;
    const d = draftFromClient(client);
    expect(d).toMatchObject({
      active: false,
      isPublic: true,
      redirectUris: "https://a\nhttps://b",
      accessTtlMinutes: "10",
      refreshTtlDays: "1",
      idTtlMinutes: "",
      mfaPolicy: "required",
      scopes: [{ id: "s1", required: true }],
      roleIds: ["r1"],
    });
  });
});
